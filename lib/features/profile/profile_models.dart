class DriverProfile {
  const DriverProfile({
    required this.name,
    required this.employeeId,
    required this.assignedTruck,
    required this.phoneNumber,
    required this.email,
    required this.status,
  });

  final String name;
  final String employeeId;
  final String assignedTruck;
  final String phoneNumber;
  final String email;
  final String status;
}